// Copies the @gutenye/ocr-browser model files and the onnxruntime-web wasm
// assets into public/ so they're served as static assets by Vite (in both
// `dev` and the built `dist/`). Run as a `postinstall` step.

import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runtimeInfo } from './runtime-version.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

const modelDst = join(repoRoot, 'public', 'models');
const { ortDir, modelCache } = runtimeInfo(repoRoot);
const ortDst   = join(repoRoot, 'public', ortDir);

mkdirSync(modelDst, { recursive: true });
mkdirSync(ortDst,   { recursive: true });

// Drop runtime folders left by earlier installs (the old unversioned /ort/ and
// previous versions) so they are never shipped.
for (const name of readdirSync(join(repoRoot, 'public'))) {
  if (/^ort(-.+)?$/.test(name) && name !== ortDir) {
    rmSync(join(repoRoot, 'public', name), { recursive: true, force: true });
  }
}

const modelSrc = join(repoRoot, 'node_modules', '@gutenye', 'ocr-models', 'assets');
for (const name of [
  'ch_PP-OCRv4_det_infer.onnx',
  'ch_PP-OCRv4_rec_infer.onnx',
  'ppocr_keys_v1.txt'
]) {
  const src = join(modelSrc, name);
  if (!existsSync(src)) {
    console.warn(`[copy-models] missing ${src}`);
    continue;
  }
  copyFileSync(src, join(modelDst, name));
}

// Copy onnxruntime-web WASM + worker assets so ORT can find them at runtime.
const ortSrc = join(repoRoot, 'node_modules', 'onnxruntime-web', 'dist');
if (existsSync(ortSrc)) {
  for (const f of readdirSync(ortSrc)) {
    if (/\.(wasm|mjs)$/.test(f) || /^ort-.*\.js$/.test(f)) {
      copyFileSync(join(ortSrc, f), join(ortDst, f));
    }
  }
} else {
  console.warn('[copy-models] onnxruntime-web/dist not found — ORT WASM will not be served');
}

// Copy Roboto TTF fonts used by the PDFKit PDF export into public/fonts/ so
// they can be fetched by the browser at runtime. The fonts live in pdfmake's
// package so they are available wherever pdfmake is installed.
const fontDst = join(repoRoot, 'public', 'fonts');
mkdirSync(fontDst, { recursive: true });
const fontSrc = join(repoRoot, 'node_modules', 'pdfmake', 'fonts', 'Roboto');
if (existsSync(fontSrc)) {
  for (const name of ['Roboto-Regular.ttf', 'Roboto-Medium.ttf']) {
    copyFileSync(join(fontSrc, name), join(fontDst, name));
  }
} else {
  console.warn('[copy-models] pdfmake Roboto fonts not found — PDF export font will be missing');
}

// Copy Roboto variable fonts (self-hosted; source committed to src/fonts/).
// These are served by the browser for the app UI typeface (not for PDF).
const varFontSrc = join(repoRoot, 'src', 'fonts');
for (const name of ['Roboto-VariableFont.ttf', 'Roboto-Italic-VariableFont.ttf']) {
  const src = join(varFontSrc, name);
  if (existsSync(src)) {
    copyFileSync(src, join(fontDst, name));
  } else {
    console.warn(`[copy-models] Roboto variable font not found: ${src}`);
  }
}

// Cross-origin isolation and model caching are handled by the service worker.
// Its source is scripts/sw.template.js (hand-written); the versioned runtime
// folder and cache name are filled in here to produce public/sw.js.
const swTemplate = readFileSync(join(__dirname, 'sw.template.js'), 'utf8');
const swOut = swTemplate
  .replaceAll('__ORT_DIR__', ortDir)
  .replaceAll('__MODEL_CACHE__', modelCache);
if (/__[A-Z_]+__/.test(swOut)) {
  throw new Error('[copy-models] unreplaced placeholder in sw.js');
}
writeFileSync(
  join(repoRoot, 'public', 'sw.js'),
  '// GENERATED by scripts/copy-models.mjs from scripts/sw.template.js. Do not edit.\n' + swOut
);

console.log('[copy-models] done');
